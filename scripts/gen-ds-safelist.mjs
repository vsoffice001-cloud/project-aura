#!/usr/bin/env node
/**
 * gen-ds-safelist.mjs — auto-generate Tailwind v4 @source safelist
 *
 * WHY: Tailwind v4 skips node_modules scanning. DS atoms in
 *   design-system/core-v2/src/ live in pnpm-symlinked node_modules from
 *   consumer's POV. ALL arbitrary-value utilities (bg-[var()] · h-[Npx]
 *   · text-[Nrem] · tracking-[Nem]) silently fail to compile → broken UI.
 *   Manual safelist in globals.css grows · drifts · always behind.
 *
 * WHAT: Reads every .tsx file in design-system/core-v2/src/{atoms,molecules,organisms}/
 *   Extracts every Tailwind utility seen in className strings · dedupes ·
 *   writes one @source inline() block to a generated file consumer imports.
 *
 * WHEN: Run before consumer build · OR pre-handover · OR after DS atom change.
 *   `node scripts/gen-ds-safelist.mjs`
 * WHEN NOT: For shadcn/ui atoms (those expose className via cva variants ·
 *   different pattern · use shadcn registry instead).
 *
 * HOW:
 *   1. Walk design-system/core-v2/src/{atoms,molecules,organisms} recursively
 *   2. For each .tsx · grep className/cn() string literals
 *   3. Tokenize on whitespace · keep tokens matching Tailwind arbitrary/known util shape
 *   4. Filter to: bg-[ · text-[ · border-[ · h-[ · w-[ · min-h-[ · min-w-[ · max-w-[ ·
 *      p-[ · px-[ · py-[ · m-[ · gap-[ · rounded-[ · shadow-[ · tracking-[ · leading-[ ·
 *      font-[ · ring-[ · outline-[ · py-N · px-N · gap-N (where N is integer or 0.5)
 *   5. Dedupe + sort
 *   6. Emit to design-system/core-v2/src/styles/_safelist.generated.css
 */

import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const DS_SRC = join(ROOT, 'design-system/core-v2/src');
const OUT_FILE = join(DS_SRC, 'styles/_safelist.generated.css');

const SCAN_DIRS = ['atoms', 'molecules', 'organisms'];

const ARBITRARY_PATTERNS = [
  /\b(bg|text|border|fill|stroke|ring|outline|caret|accent|decoration|placeholder)-\[[^\]]+\]/g,
  /\b(h|w|min-h|min-w|max-h|max-w|size)-\[[^\]]+\]/g,
  /\b(p|px|py|pt|pr|pb|pl|m|mx|my|mt|mr|mb|ml|gap|gap-x|gap-y|space-x|space-y|inset|top|right|bottom|left)-\[[^\]]+\]/g,
  /\b(rounded|shadow|tracking|leading|font|text|indent|order|grid-cols|grid-rows|col-span|row-span|z|opacity)-\[[^\]]+\]/g,
  /\b(translate-x|translate-y|rotate|scale|skew-x|skew-y|origin)-\[[^\]]+\]/g,
  /\b(duration|delay|ease)-\[[^\]]+\]/g,
  /\b(grid-cols|grid-rows)-\[[^\]]+\]/g,
  /\b(blur|brightness|contrast|grayscale|hue-rotate|invert|saturate|sepia|backdrop-blur)-\[[^\]]+\]/g,
];

const NUMERIC_PATTERNS = [
  /\b(p|px|py|pt|pr|pb|pl|m|mx|my|mt|mr|mb|ml|gap|gap-x|gap-y|space-x|space-y)-\d+(?:\.\d+)?\b/g,
  /\b(?:sm|md|lg|xl|2xl):(?:p|px|py|pt|pr|pb|pl|m|mx|my|mt|mr|mb|ml|gap|gap-x|gap-y)-\d+(?:\.\d+)?\b/g,
  /\b(h|w|min-h|min-w|max-h|max-w)-(?:full|screen|auto|fit|min|max|0|0\.5|1|1\.5|2|2\.5|3|3\.5|4|5|6|7|8|9|10|11|12|14|16|20|24|28|32|36|40|44|48|52|56|60|64|72|80|96)\b/g,
  /\btext-(?:xs|sm|base|lg|xl|2xl|3xl|4xl|5xl|6xl|7xl|8xl|9xl)\b/g,
  /\b(?:sm|md|lg|xl|2xl):text-(?:xs|sm|base|lg|xl|2xl|3xl|4xl|5xl|6xl|7xl|8xl|9xl)\b/g,
];

const PSEUDO_PATTERNS = [
  /\b(?:hover|focus|focus-visible|active|disabled|group-hover|peer-hover|md|sm|lg|xl):[a-z-]+(?:-\[[^\]]+\])?/g,
];

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) out.push(...walk(full));
    else if (entry.endsWith('.tsx') || entry.endsWith('.ts')) out.push(full);
  }
  return out;
}

function extractClasses(content) {
  const found = new Set();
  for (const pat of [...ARBITRARY_PATTERNS, ...NUMERIC_PATTERNS, ...PSEUDO_PATTERNS]) {
    const matches = content.match(pat);
    if (matches) matches.forEach((m) => found.add(m));
  }
  /* Drop tokens containing template-literal interpolation ${...} or other invalid CSS chars.
     WHY: scanner finds `h-[var(--button-height-${size})]` strings in DS source comments + old code.
     Emitting them breaks PostCSS parser. */
  return new Set([...found].filter((c) => !c.includes('${') && !c.includes('$')));
}

function main() {
  const allClasses = new Set();
  let fileCount = 0;
  for (const sub of SCAN_DIRS) {
    const dir = join(DS_SRC, sub);
    const files = walk(dir);
    fileCount += files.length;
    for (const f of files) {
      const content = readFileSync(f, 'utf-8');
      const found = extractClasses(content);
      found.forEach((c) => allClasses.add(c));
    }
  }
  const sorted = [...allClasses].sort();
  const header = `/* AUTO-GENERATED · DO NOT EDIT BY HAND
 * Generated by scripts/gen-ds-safelist.mjs
 * Scanned: ${fileCount} files in design-system/core-v2/src/{${SCAN_DIRS.join(',')}}
 * Classes: ${sorted.length}
 *
 * Import in consumer globals.css: @import '@kenresearch/design-system/styles/_safelist.generated.css';
 */\n\n`;
  const chunks = [];
  for (let i = 0; i < sorted.length; i += 10) {
    chunks.push(`@source inline("${sorted.slice(i, i + 10).join(' ')}");`);
  }
  const body = chunks.join('\n');
  writeFileSync(OUT_FILE, header + body + '\n');
  console.log(`✓ safelist generated · ${sorted.length} classes · ${fileCount} files scanned · → ${OUT_FILE}`);
}

main();
